type PluralLeaf = { readonly one: string; readonly other: string }

/** Same keys as `fr`, but any string value (used to type other languages). */
type Shape<T> = {
  readonly [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends PluralLeaf
      ? PluralLeaf
      : Shape<T[K]>
}

